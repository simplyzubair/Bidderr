// Builds every Bidderr brand file from one design: a handwritten "B" (Kaushan Script, SIL Open
// Font License) with a fountain pen whose nib draws the ink line under it.
//
//   npm i --no-save opentype.js@1 sharp@0.33 && node scripts/makeBranding.js
//
// Writes: branding/logo.svg (square tile), branding/mark.svg (round, for bubbles), PNG icons for
// Windows, the tray, the website and Android, and the Android adaptive-icon vector.
const fs = require('fs');
const os = require('os');
const path = require('path');
const https = require('https');
const opentype = require('opentype.js');
const sharp = require('sharp');

const root = path.join(__dirname, '..');
const FONT_URL = 'https://github.com/google/fonts/raw/main/ofl/kaushanscript/KaushanScript-Regular.ttf';
const COLORS = { light: '#34d399', mid: '#10b981', dark: '#0f766e', ink: '#ffffff' };

function download(url, file) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode >= 300 && res.headers.location) return download(res.headers.location, file).then(resolve, reject);
      if (res.statusCode !== 200) return reject(new Error(`download failed: ${res.statusCode}`));
      res.pipe(fs.createWriteStream(file)).on('finish', resolve);
    }).on('error', reject);
  });
}

// ---------- the drawing (in a 512 x 512 box) ----------

function glyphPath(font) {
  const size = 300;
  const cx = 240;
  const cy = 222;
  let p = font.getPath('B', 0, 0, 400);
  let bb = p.getBoundingBox();
  const s = size / Math.max(bb.x2 - bb.x1, bb.y2 - bb.y1);
  p = font.getPath('B', 0, 0, 400 * s);
  bb = p.getBoundingBox();
  return font.getPath('B', cx - (bb.x1 + bb.x2) / 2, cy - (bb.y1 + bb.y2) / 2, 400 * s).toPathData(1);
}

// Ink line from the nib tip (x, y) sweeping left, thick near the pen, thin at the start.
const swashPath = (x, y, len) =>
  `M${x} ${y}C${x - len * 0.25} ${y + 24} ${x - len * 0.72} ${y + 26} ${x - len} ${y + 6}` +
  `C${x - len - 6} ${y + 3} ${x - len - 4} ${y - 5} ${x - len + 3} ${y - 4}` +
  `C${x - len * 0.7} ${y + 10} ${x - len * 0.27} ${y + 7} ${x} ${y}Z`;

// Rounded rectangle as a path (Android vectors have no <rect>).
const roundRect = (x, y, w, h, r) =>
  `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}` +
  `H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;

// Fountain pen, nib tip at (0,0) pointing down. [path, colour] pairs.
const PEN_PARTS = [
  ['M0 0C-7 -22 -22 -52 -25 -84L-25 -104L25 -104L25 -84C22 -52 7 -22 0 0Z', '#ffffff'], // nib
  ['M-1.8 -6L-1.8 -58L1.8 -58L1.8 -6Z', COLORS.dark], // slit
  ['M-7.5 -64A7.5 7.5 0 1 0 7.5 -64A7.5 7.5 0 1 0 -7.5 -64Z', COLORS.dark], // breather hole
  [roundRect(-30, -122, 60, 18, 4), '#d1fae5'], // grip ring
  [roundRect(-27, -250, 54, 128, 14), '#ecfdf5'], // body
  ['M-27 -168H27V-159H-27Z', '#a7f3d0'], // band
];
const PEN = { x: 372, y: 398, angle: 40, scale: 0.6 };

function artSvg(glyph) {
  const pen = PEN_PARTS.map(([d, c]) => `<path d="${d}" fill="${c}"/>`).join('');
  return `<path fill="${COLORS.ink}" stroke="${COLORS.ink}" stroke-width="6" stroke-linejoin="round" d="${glyph}"/>` +
    `<path fill="${COLORS.ink}" d="${swashPath(PEN.x, PEN.y, 250)}"/>` +
    `<g transform="translate(${PEN.x} ${PEN.y}) rotate(${PEN.angle}) scale(${PEN.scale})">${pen}</g>`;
}

const defs = `<defs><linearGradient id="bidderr-tile" x1="0" y1="0" x2="1" y2="1">` +
  `<stop offset="0" stop-color="${COLORS.light}"/><stop offset=".55" stop-color="${COLORS.mid}"/><stop offset="1" stop-color="${COLORS.dark}"/>` +
  `</linearGradient><filter id="bidderr-shadow" x="-20%" y="-20%" width="140%" height="140%">` +
  `<feDropShadow dx="0" dy="6" stdDeviation="7" flood-color="#064e3b" flood-opacity=".35"/></filter></defs>`;

// shape: 'tile' (rounded square app icon) or 'round' (circle, for bubbles).
function logoSvg(glyph, shape) {
  const bg = shape === 'round'
    ? '<circle cx="256" cy="256" r="256" fill="url(#bidderr-tile)"/>'
    : '<rect width="512" height="512" rx="116" fill="url(#bidderr-tile)"/>';
  // The round mark is a little smaller inside, so nothing touches the circle edge.
  const inner = shape === 'round' ? 'transform="translate(256 262) scale(0.84) translate(-256 -256)"' : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${defs}${bg}` +
    `<g filter="url(#bidderr-shadow)"><g ${inner}>${artSvg(glyph)}</g></g></svg>\n`;
}

// Android adaptive icon foreground: same drawing, scaled into the 66/108 safe zone.
function androidForeground(glyph) {
  const pen = PEN_PARTS.map(([d, c]) =>
    `            <path android:fillColor="#FF${c.slice(1).toUpperCase()}" android:pathData="${d}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/makeBranding.js: handwritten B + fountain pen. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="512"
    android:viewportHeight="512">
    <group android:pivotX="256" android:pivotY="256" android:scaleX="0.74" android:scaleY="0.74" android:translateY="6">
        <path android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" android:strokeWidth="6"
            android:strokeLineJoin="round" android:pathData="${glyph}" />
        <path android:fillColor="#FFFFFFFF" android:pathData="${swashPath(PEN.x, PEN.y, 250)}" />
        <group android:translateX="${PEN.x}" android:translateY="${PEN.y}" android:rotation="${PEN.angle}"
            android:scaleX="${PEN.scale}" android:scaleY="${PEN.scale}">
${pen}
        </group>
    </group>
</vector>
`;
}

(async () => {
  const fontFile = path.join(os.tmpdir(), 'KaushanScript-Regular.ttf');
  if (!fs.existsSync(fontFile)) await download(FONT_URL, fontFile);
  const glyph = glyphPath(opentype.loadSync(fontFile));

  const tile = logoSvg(glyph, 'tile');
  const round = logoSvg(glyph, 'round');
  const write = (file, data) => {
    const target = path.join(root, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, data);
    console.log(`wrote ${file}`);
  };
  write('branding/logo.svg', tile);
  write('branding/mark.svg', round);
  write('website/logo.svg', tile);
  write('android/app/src/main/res/drawable/ic_launcher_foreground.xml', androidForeground(glyph));

  const png = async (svg, file, size) => {
    const target = path.join(root, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    await sharp(Buffer.from(svg), { density: Math.max(72, (size / 512) * 72 * 4) }).resize(size, size).png().toFile(target);
    console.log(`wrote ${file} (${size}px)`);
  };
  await png(tile, 'public/icon.png', 256);
  await png(tile, 'public/tray.png', 32);
  await png(tile, 'website/icon.png', 256);
  await png(round, 'shared/img/mark.png', 128); // bubbles in the Android pages
  for (const [dir, size] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
    await png(tile, `android/app/src/main/res/mipmap-${dir}/ic_launcher.png`, size);
  }
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
